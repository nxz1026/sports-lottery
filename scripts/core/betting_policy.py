"""core.betting_policy —— 投注口径数字的**唯一真源**（2026-10-23 新增）。

⚠️ **为什么要有这个模块**（P2-H4 事故，实测）：

用户可见文案里的数字以前是**手打**的。例如荐单面板上印着：

    「…单边投注要先扛掉这笔水 ⇒ EV 必须不低于水位才谈得上盈利
      （推荐端阈值已对齐为 EV ≥ 12.9%）」

而代码里真正的阈值是 ``MIN_EV = 0.05``（**5%**）⇒ **两处各写各的** ⇒
文案可以（而且已经）漂移成**假话**：用户被告知一个**不存在的策略**。
静态审计、单测、守门**全都没抓到** —— 因为守门只查了
「文案里有没有 12.9%」「有没有 25~33%」，**没查「12.9% 是不是那个阈值」**。

⇒ 现在的做法：**所有会渲染给用户的口径数字都从这里派生** ⇒ 数值**不可能漂移**。
⇒ 并且加一条**通用**守门：用户可见文本里出现的「EV 阈值」「水位」数字，
  必须与这里的常量一致（不再手写具体数字）。

口径说明（写在这里，避免下次又有人把水位当门槛）：

- ``MIN_EV`` / ``MIN_P`` 是**产品政策值**（路线图 §6.6.5.1：暂不动，等 n ≥ 100 再校准）。
- ``WATER_LEVEL_MEASURED`` 是**市场水位**（生产实测），**不是**推荐门槛：
  设 ``m = 1 + 水位``、``q`` = 去水后市场概率、``SP = 1/(m·q)``，则
  单位 EV ``= p·SP − 1 = p/(m·q) − 1`` ⇒ **EV > 0 ⟺ p/q > m**
  ⇒ 对**单边**投注「扛掉这笔水」= **EV > 0**（**不是** EV ≥ 水位）；
  水位只在**串关**上才需要单独扛（门槛 ``mⁿ``）。
  推导全文见 ``scripts/decision/recommend.py`` 的阈值注释块。
"""
from __future__ import annotations

# ── 阈值（产品政策值；路线图 §6.6.5.1「暂不动，等 n ≥ 100 再校准」）────────────
MIN_EV = 0.05           # 单位 EV ≥ 5%（在「正 EV 之外再加一道安全垫」）
MIN_P = 0.10            # 模型概率 ≥ 10%（不要长尾彩票）—— **方向级**排除

# ── 市场水位（**生产实测**，2026-10-23）─────────────────────────────────────
#   竞彩 had 三项 SP 的隐含概率和 − 1 = 12.9%
#   （当日实测 SP 1.86/3.70/3.12 ⇒ 1/1.86+1/3.70+1/3.12 = 1.1284 ⇒ 12.84%，互相印证；
#     等额三侧每元回报 ≈ 0.89 元 ⇒ 水位 ≈ 11~13%）。
WATER_LEVEL_MEASURED = 0.129

# 守门用的容差：文案里的「12.9%」与常量 0.129 的允许偏差
WATER_LEVEL_TOL = 0.0005


def pct_text(value: float) -> str:
    """比例 → 人看的百分比：``0.05`` → ``5%``、``0.129`` → ``12.9%``。

    ⚠️ 必须走这个函数，**不许**在文案里手写 ``"12.9%"`` / ``"5%"``。
    """
    pct = round(value * 100, 1)
    if abs(pct - round(pct)) < 1e-9:
        return f"{int(round(pct))}%"
    return f"{pct:g}%"


def threshold_text(value: float) -> str:
    """门槛的**双表示**：「``0.05（5%）``」—— 比例给复算用，百分比给人看。

    ⚠️ 荐单 note 要能**复算**当时生效的门槛 ⇒ 必须保留比例；
    但只给比例（0.05）人会以为是 0.05% ⇒ 百分比一起给。
    """
    return f"{value:g}（{pct_text(value)}）"


# ── 派生好的文案片段（**只读**，直接用）────────────────────────────────────
EV_THRESHOLD_TEXT = f"EV ≥ {pct_text(MIN_EV)}"
WATER_LEVEL_TEXT = pct_text(WATER_LEVEL_MEASURED)

# 水位因子 m = 1 + 水位（代数里 SP = 1/(m·q) 用的那个 m）
WATER_FACTOR = 1.0 + WATER_LEVEL_MEASURED
WATER_FACTOR_TEXT = f"{WATER_FACTOR:g}"          # "1.129"

# 等额三侧投注的每元回报 ≈ 1/m（用来交叉印证水位口径）
WATER_RETURN_TEXT = f"{1.0 / WATER_FACTOR:.2f}"  # "0.89"

# 水位区间（把实测值向下/向上取整到整百分比，再各放宽 1 ⇒ "11~13%"）
WATER_RANGE_TEXT = (f"{int(WATER_LEVEL_MEASURED * 100) - 1}"
                    f"~{int(-(-WATER_LEVEL_MEASURED * 100 // 1))}%")
