from __future__ import annotations

# ── 阈值（产品政策值）──────────────────────────────────────────────────────
# ⚠️ **2026-10-23 订正**：原 ``MIN_EV = 0.05``（5%），依据是路线图 §6.6.5.1
#   「暂不动，等 n ≥ 100 再校准」。⇒ **用户 2026-10-23 明确批准**提到实测水位
#   **12.9%**（只推明显高于「扛水」盈亏平衡线的场次；实测 8 天 39 条 → 25 条达标）。
#   ⚠️ 「单边扛水」的数学门槛**仍然是 EV > 0**；EV ≥ 12.9% 等价于 p/q ≥ m² ≈ 1.275，
#   **比扛水更严** —— 这是**保守筛选**，不是数学等价（详见模块 docstring）。
MIN_EV = 0.129          # 单位 EV ≥ 12.9%（= 实测水位；用户 2026-10-23 批准的阈值政策变更）
MIN_P = 0.10            # 模型概率 ≥ 10%（不要长尾彩票）—— **方向级**排除

# ── 市场水位（**生产实测**，2026-10-23）─────────────────────────────────────
#   竞彩 had 三项 SP 的隐含概率和 − 1 = 12.9%
#   （当日实测 SP 1.86/3.70/3.12 ⇒ 1/1.86+1/3.70+1/3.12 = 1.1284 ⇒ 12.84%，互相印证；
#     等额三侧每元回报 ≈ 0.89 元 ⇒ 水位 ≈ 11~13%）。
WATER_LEVEL_MEASURED = 0.129

# 守门用的容差：文案里的「12.9%」与常量 0.129 的允许偏差
WATER_LEVEL_TOL = 0.0005


def pct_text(value: float) -> str:
    """比例 → 人看的百分比：``0.05`` → ``5%``、``0.129`` → ``12.9%``。

    ⚠️ 必须走这个函数，**不许**在文案里手写 ``"12.9%"`` / ``"5%"``。
    """
    pct = round(value * 100, 1)
    if abs(pct - round(pct)) < 1e-9:
        return f"{int(round(pct))}%"
    return f"{pct:g}%"


def threshold_text(value: float) -> str:
    """门槛的**双表示**：「``0.05（5%）``」—— 比例给复算用，百分比给人看。

    ⚠️ 荐单 note 要能**复算**当时生效的门槛 ⇒ 必须保留比例；
    但只给比例（0.05）人会以为是 0.05% ⇒ 百分比一起给。
    """
    return f"{value:g}（{pct_text(value)}）"


# ── 派生好的文案片段（**只读**，直接用）────────────────────────────────────
EV_THRESHOLD_TEXT = f"EV ≥ {pct_text(MIN_EV)}"
WATER_LEVEL_TEXT = pct_text(WATER_LEVEL_MEASURED)

# 水位因子 m = 1 + 水位（代数里 SP = 1/(m·q) 用的那个 m）
WATER_FACTOR = 1.0 + WATER_LEVEL_MEASURED
WATER_FACTOR_TEXT = f"{WATER_FACTOR:g}"          # "1.129"

# EV ≥ MIN_EV 的等价条件：p/q ≥ m·(1+MIN_EV)
#   （m = 1+水位；EV = p/(m·q) − 1 ≥ MIN_EV ⟺ p/q ≥ m(1+MIN_EV)）
# ⚠️ 当 MIN_EV = 水位 时，这个值就是 m² ≈ 1.275 ⇒ 比「扛水」(p/q > m) **更严**。
EV_FACTOR = WATER_FACTOR * (1.0 + MIN_EV)
EV_FACTOR_TEXT = f"{EV_FACTOR:.3f}"                # "1.275"
# EV ≥ MIN_EV 等价于「模型概率要比去水后的市场概率高出多少 %」（给人看的说法）
EV_EDGE_PCT = (EV_FACTOR - 1.0) * 100.0
EV_EDGE_TEXT = f"{EV_EDGE_PCT:.1f}%"                # "27.5%"

# 单边「扛水」的**数学门槛**（代数恒等式 ⇒ 永不漂移）：EV > 0 ⟺ p/q > m
# ⚠️ 它**不是**产品政策数字 ⇒ 用户可见文案里用这个**派生片段**，
#    不许手写「EV > 0」（手写会被 UVC 判定②当成「手写口径数字」抓出来）。
EV_BREAKEVEN_TEXT = "EV > 0"

# 阈值政策的**批准记录**（谁、什么时候批准把阈值提到实测水位）
EV_APPROVAL_DATE = "2026-10-23"

# 等额三侧投注的每元回报 ≈ 1/m（用来交叉印证水位口径）
WATER_RETURN_TEXT = f"{1.0 / WATER_FACTOR:.2f}"  # "0.89"

# 水位区间（把实测值向下/向上取整到整百分比，再各放宽 1 ⇒ "11~13%"）
WATER_RANGE_TEXT = (f"{int(WATER_LEVEL_MEASURED * 100) - 1}"
                    f"~{int(-(-WATER_LEVEL_MEASURED * 100 // 1))}%")

# ── 阈值变更的**实测取证快照**（2026-10-23 用户批准的那次变更）──────────────
#   生产 `analysis.ev_report` 实测（8 天 39 条）：
#     ≥5%    → 全部 39 条达标；
#     ≥12.9% → 剩 25 条（保留 64%），达标最低 EV = 0.141704。
#   ⇒ 2026-10-16 那唯一一条 EV 0.1234 ⇒ **新门槛下那天一条不推**（预期代价，非故障）。
# ⚠️ 这是**带日期的取证快照**，不是实时统计（实时数在 DB 里，别混为一谈）。
# ⚠️ **不许**把这些数字直接手抄进用户可见文案 —— 必须用下面的 ``EV_SNAPSHOT_TEXT``
#    派生（P2-I 纪律：用户可见文案里的数字一律从真源派生 ⇒ 不可能漂移）。
EV_SNAPSHOT_DATE = "2026-10-23"
EV_SNAPSHOT_DAYS = 8
EV_SNAPSHOT_N_ALL = 39
EV_SNAPSHOT_N_KEPT = 25
EV_SNAPSHOT_MIN_EV = 0.141704
EV_SNAPSHOT_TEXT = (
    f"{EV_SNAPSHOT_DATE} 实测快照：{EV_SNAPSHOT_DAYS} 天共 {EV_SNAPSHOT_N_ALL} 条荐单，"
    f"按此门槛剩 {EV_SNAPSHOT_N_KEPT} 条（保留 "
    f"{EV_SNAPSHOT_N_KEPT * 100 // EV_SNAPSHOT_N_ALL}%），"
    f"达标最低 EV {EV_SNAPSHOT_MIN_EV:.4f}"
)


def policy_consistency_errors() -> list[str]:
    """政策一致性自检（守门 + 单测调用；返回空列表 = 一致）。

    ⚠️ **为什么要有这条**：``WATER_LEVEL_MEASURED`` 是**实测值**（会随市场重测），
    而 ``MIN_EV`` 是**产品政策值**（只有用户批准才能改）。
    ⇒ 两者一旦不等 ⇒ 要么「改了政策没记进订正」，要么「重测了水位没重审阈值」
    ⇒ **必须显式暴露**，不许静默漂移（P2-I 纪律：数值不可能悄悄改）。

    ⇒ 重测水位时，**必须**同时显式重审 ``MIN_EV``（哪怕结论是「保持不变」，
      也要在常量旁写明复核日期与结论）。
    """
    errs: list[str] = []
    if abs(MIN_EV - WATER_LEVEL_MEASURED) > 1e-9:
        errs.append(
            f"MIN_EV({MIN_EV}) != WATER_LEVEL_MEASURED({WATER_LEVEL_MEASURED})："
            "实测水位变了 ⇒ 必须显式重审推荐端阈值（政策值只有用户批准才能改）")
    # 「EV ≥ MIN_EV」必须严格严于「扛水」（p/q > m），否则文案里的「更严一道」是假话
    if EV_FACTOR <= WATER_FACTOR:
        errs.append(
            f"EV_FACTOR({EV_FACTOR:.4f}) 必须 > WATER_FACTOR({WATER_FACTOR:.4f})："
            "否则「阈值比扛水更严一道」不成立")
    return errs
